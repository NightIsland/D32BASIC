#!/usr/bin/env python3
"""Print the Dragon BASIC token table as Markdown, read from a ROM image.

Part of D32BASIC (GPLv3). Usage: dump_tokens.py ROM > docs/spec/tokens.md
Keywords are stored with bit 7 set on their last character. Statement
tokens start at $80; function tokens are two bytes, $FF followed by $80+n.
"""
import sys

rom = open(sys.argv[1], 'rb').read()
assert len(rom) == 0x4000


def table(start_word, count):
    p = rom.find(start_word[:-1].encode() + bytes([ord(start_word[-1]) | 0x80]))
    assert p >= 0, start_word
    out = []
    for _ in range(count):
        w = ''
        while True:
            b = rom[p]; p += 1
            w += chr(b & 0x7F)
            if b & 0x80:
                break
        out.append(w)
    return out, 0x8000 + rom.find(start_word[:-1].encode() + bytes([ord(start_word[-1]) | 0x80]))


# 78 statement tokens ($80-$CD) and 34 function tokens in the Dragon 32 ROM
stm, stm_at = table('FOR', 78)
fun, fun_at = table('SGN', 34)
print('# Dragon BASIC tokens\n')
print('Generated by `tools/oracle/dump_tokens.py` from the Dragon 32-mode ROM.')
print('Statement keywords are one byte; function keywords are `$FF` then a second byte.\n')
print('## Statements and operators (one byte)\n')
print('| Token | Keyword | Token | Keyword | Token | Keyword |')
print('|---|---|---|---|---|---|')
rows = [('$%02X' % (0x80 + i), '`%s`' % w) for i, w in enumerate(stm)]
for i in range(0, len(rows), 3):
    cells = rows[i:i + 3] + [('', '')] * (3 - len(rows[i:i + 3]))
    print('| ' + ' | '.join('%s | %s' % c for c in cells) + ' |')
print('\n## Functions (`$FF` + one byte)\n')
print('| Token | Keyword | Token | Keyword | Token | Keyword |')
print('|---|---|---|---|---|---|')
rows = [('$FF $%02X' % (0x80 + i), '`%s`' % w) for i, w in enumerate(fun)]
for i in range(0, len(rows), 3):
    cells = rows[i:i + 3] + [('', '')] * (3 - len(rows[i:i + 3]))
    print('| ' + ' | '.join('%s | %s' % c for c in cells) + ' |')
