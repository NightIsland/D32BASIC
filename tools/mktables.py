#!/usr/bin/env python3
"""Generate src/tables_gen.inc: Dragon BASIC reserved words, token
equates and dispatch tables (token order from docs/spec/tokens.md)."""
stm = "FOR GO REM ' ELSE IF DATA PRINT ON INPUT END NEXT DIM READ LET RUN RESTORE RETURN STOP POKE CONT LIST CLEAR NEW DEF CLOAD CSAVE OPEN CLOSE LLIST SET RESET CLS MOTOR SOUND AUDIO EXEC SKIPF DEL EDIT TRON TROFF LINE PCLS PSET PRESET SCREEN PCLEAR COLOR CIRCLE PAINT GET PUT DRAW PCOPY PMODE PLAY DLOAD RENUM".split()
ops = "TAB( TO SUB FN THEN NOT STEP OFF + - * / ^ AND OR > = < USING".split()
fun = "SGN INT ABS POS RND SQR LOG EXP SIN COS TAN ATN PEEK LEN STR$ VAL ASC CHR$ EOF JOYSTK FIX HEX$ LEFT$ RIGHT$ MID$ POINT INKEY$ MEM VARPTR INSTR TIMER PPOINT STRING$ USR".split()
# DragonDOS 1.0 keywords (from its ROM): statements $CE-$E7, functions $FF $A2-$A8.
dos = "AUTO BACKUP BEEP BOOT CHAIN COPY CREATE DIR DRIVE DSKINIT FREAD FWRITE ERROR KILL LOAD MERGE PROTECT WAIT RENAME SAVE SREAD SWRITE VERIFY FROM FLREAD SWAP".split()
dosfun = "LOF FREE ERL ERR HIMEM LOC FRE$".split()
assert len(stm) + len(ops) == 78 and len(fun) == 34 and len(dos) == 26
fun += dosfun

# Statements without a handler yet dispatch to st_unimpl (?SN for now).
handlers = {"FOR": "st_for", "GO": "st_go", "REM": "st_rem", "'": "st_rem",
            "ELSE": "st_rem", "IF": "st_if", "DATA": "st_data", "PRINT": "st_print",
            "ON": "st_on", "INPUT": "st_input", "END": "st_end", "NEXT": "st_next",
            "DIM": "st_dim", "READ": "st_read", "LET": "st_let", "RUN": "st_run",
            "RESTORE": "st_restore", "RETURN": "st_return", "STOP": "st_stop",
            "POKE": "st_poke", "CONT": "st_cont", "LIST": "st_list", "CLEAR": "st_clear",
            "NEW": "st_new", "DEF": "st_def", "CLS": "st_cls", "DEL": "st_del",
            "EDIT": "st_edit", "TRON": "st_tron", "TROFF": "st_troff", "RENUM": "st_renum",
            "EXEC": "st_exec", "PCLEAR": "st_pclear", "PMODE": "st_pmode",
            "SCREEN": "st_screen", "COLOR": "st_color", "PCLS": "st_pcls",
            "PCOPY": "st_pcopy", "PSET": "st_pset", "PRESET": "st_preset",
            "LINE": "st_line", "GET": "st_get", "PUT": "st_put",
            "PAINT": "st_paint", "CIRCLE": "st_circle", "DRAW": "st_draw", "SET": "st_set", "RESET": "st_reset", "CLOAD": "st_cload", "CSAVE": "st_csave",
            "DIR": "st_dir", "KILL": "st_kill", "LOAD": "st_load", "MERGE": "st_merge",
            "RENAME": "st_rename", "SAVE": "st_save",
            "SOUND": "st_sound", "PLAY": "st_play", "AUDIO": "st_audio", "MOTOR": "st_motor",
            "OPEN": "st_open", "CLOSE": "st_close", "LLIST": "st_llist"}
funh = {"SGN": "fn_sgn", "INT": "fn_int", "ABS": "fn_abs", "POS": "fn_pos", "RND": "fn_rnd",
        "SQR": "fn_sqr", "LOG": "fn_log", "EXP": "fn_exp", "SIN": "fn_sin", "COS": "fn_cos",
        "TAN": "fn_tan", "ATN": "fn_atn", "PEEK": "fn_peek", "LEN": "fn_len", "STR$": "fn_str",
        "VAL": "fn_val", "ASC": "fn_asc", "CHR$": "fn_chr", "FIX": "fn_fix", "HEX$": "fn_hex",
        "LEFT$": "fn_left", "RIGHT$": "fn_right", "MID$": "fn_mid", "INKEY$": "fn_inkey",
        "MEM": "fn_mem", "VARPTR": "fn_varptr", "INSTR": "fn_instr", "TIMER": "fn_timer",
        "STRING$": "fn_string", "USR": "fn_usr",
        "POINT": "fn_point", "PPOINT": "fn_ppoint", "JOYSTK": "fn_joystk", "EOF": "fn_eof"}
names = {"'": "SNGQ", "TAB(": "TAB", "+": "PLUS", "-": "MINUS", "*": "MUL", "/": "DIV",
         "^": "POW", ">": "GREATER", "=": "EQUAL", "<": "LESS"}

def dci(w):
    b = [ord(c) | (0x80 if i == len(w) - 1 else 0) for i, c in enumerate(w)]
    return "        db " + ",".join("$%02X" % v for v in b) + "   ; " + w

L = ["; Generated by tools/mktables.py - do not edit.",
     "; Reserved words: last character has bit 7 set.", "",
     "NUM_STM         EQU %d" % len(stm),
     "NUM_NORMAL      EQU %d" % (len(stm) + len(ops) + len(dos)),
     "TK_DOSFST       EQU $%02X" % (0x80 + len(stm) + len(ops)),
     "NUM_DOS         EQU %d" % len(dos),
     "NUM_FUN         EQU %d" % len(fun), ""]
for i, w in enumerate(stm + ops + dos):
    L.append("TK_%-12s EQU $%02X" % (names.get(w, w.replace("$", "")), 0x80 + i))
for i, w in enumerate(fun):
    L.append("FN_%-12s EQU $%02X" % (w.replace("$", "S"), 0x80 + i))
L += ["", "reslst:"] + [dci(w) for w in stm + ops + dos] + ["", "funlst:"] + [dci(w) for w in fun]
L += ["", "; Statement dispatch: $80 to RENUM, then the DragonDOS statements.", "stmdsp:"]
L += ["        dw %-14s; %s" % (handlers.get(w, "st_unimpl"), w) for w in stm + dos]
L += ["", "; Function dispatch.", "fundsp:"]
L += ["        dw %-14s; %s" % (funh.get(w, "fn_unimpl"), w) for w in fun]
open("src/tables_gen.inc", "w").write("\n".join(L) + "\n")
