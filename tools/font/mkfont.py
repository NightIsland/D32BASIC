def main(out):
    glyphs = []
    for line in ART.strip().splitlines():

        name, *rows = line.split()
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), line
        glyphs.append((name, rows))
    assert len(glyphs) == 64, len(glyphs)
    with open(out, "w") as f:
        f.write("; Generated by tools/font/mkfont.py - do not edit.\n")
        f.write("; 64 glyphs x 12 rows, one byte per row, bit 7 = leftmost pixel.\n")
        f.write("font_glyphs:\n")
        for name, rows in glyphs:
            data = [0, 0, 0]
            for r in rows:
                b = 0
                for i, c in enumerate(r):
                    if c == "#":
                        b |= 0x40 >> i
                data.append(b)
            data += [0, 0]
            f.write("        db " + ",".join("$%02X" % b for b in data) + "   ; %s\n" % name)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/font.inc")
